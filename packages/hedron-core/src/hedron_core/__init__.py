def _register_builtins() -> None:
    for cls in (
        Page,
        Fragment,
        Head,
        Title,
        Header,
        Main,
        Nav,
        Aside,
        Footer,
        Section,
        Container,
        Stack,
        Inline,
        Grid,
        Divider,
        Heading,
        Text,
        Link,
        Image,
        CodeBlock,
        List,
        DescriptionList,
        Table,
        Metric,
        CodeViewer,
        JSONViewer,
        Progress,
        Status,
        Toast,
        Expander,
        Tabs,
        Sidebar,
        ColorModeToggle,
        Auto,
        Card,
        Badge,
        Alert,
        Skeleton,
        Button,
        LinkButton,
        IconButton,
        Form,
        FormField,
        Label,
        TextInput,
        TextArea,
        Select,
        Checkbox,
        RadioGroup,
        SubmitButton,
        FormErrors,
    ):
        logical = (
            f"{getattr(cls, 'distribution', 'hedron-core')}:"
            f"{cls.__module__}.{getattr(cls, 'logical_name', cls.__name__)}"
        )
        register_component(
            logical_id=logical,
            name=getattr(cls, "logical_name", cls.__name__) or cls.__name__,
            module=cls.__module__,
            distribution=getattr(cls, "distribution", "hedron-core"),
            props_model=getattr(cls, "props_type", type(None)).__name__,
            slots=getattr(cls, "slots", {}),
            accessibility_notes="Uses native semantic HTML without JavaScript.",
        )


_register_builtins()
